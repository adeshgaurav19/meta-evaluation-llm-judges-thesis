"""
Produces all thesis figures from CSVs generated by analyze.py. No data computation.

Inputs:  exports/*.csv
Outputs: exports/figures/figXX_*.png, exports/figures/captions.md
"""

from pathlib import Path
import warnings

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")

ROOT    = Path(__file__).parent.parent
EXPORTS = ROOT / "exports"
FIGS    = EXPORTS / "figures"
FIGS.mkdir(exist_ok=True)

# palette

C = {
    "Clean":          "#4a7ab8",
    "True":           "#c44e52",
    "Survived":       "#8172b3",
    "Standard":       "#8c8c8c",
    "Postfilter":     "#dd8452",
    "PostfilterLLM":  "#55a868",
}

JUDGE_ORDER  = ["GPT", "GEMINI", "DEEPSEEK"]
JUDGE_LABELS = {"GPT": "GPT-5.4-nano", "GEMINI": "Gemma-4-26B", "DEEPSEEK": "DeepSeek-V3.2"}
INJ_ORDER    = ["random_noise", "adversarial_fact", "poisonedrag_style"]
INJ_LABELS   = {
    "random_noise":      "Random Noise",
    "adversarial_fact":  "Adversarial Fact",
    "poisonedrag_style": "PoisonedRAG Style",
}
NOISE_LEVELS = [0.2, 0.4, 0.6, 0.8]
SAVEKW       = dict(dpi=200, bbox_inches="tight")

plt.rcParams.update({
    "font.family":    "sans-serif",
    "font.size":      10,
    "axes.titlesize": 11,
    "axes.labelsize": 10,
})


def save(name: str):
    path = FIGS / name
    plt.savefig(path, **SAVEKW)
    plt.close()
    print(f"  {name}  ({path.stat().st_size // 1024} KB)")


# fig01

def fig01(df: pd.DataFrame):
    base = df[df["condition"] == "baseline"]
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.5), sharey=True)
    bins = np.linspace(0, 1, 21)

    for ax, judge in zip(axes, JUDGE_ORDER):
        sub    = base[base["judge"] == judge]
        clean  = sub[sub["category"] == "Clean"]["faithfulness"].dropna()
        poison = sub[sub["is_poisoned"] == True]["faithfulness"].dropna()
        ax.hist(clean,  bins=bins, alpha=0.6, color=C["Clean"], label="Clean")
        ax.hist(poison, bins=bins, alpha=0.6, color=C["True"],  label="Poisoned")
        ax.axvline(0.5, color="black", lw=1, ls="--", label="0.5 threshold")
        ax.set_title(JUDGE_LABELS[judge])
        ax.set_xlabel("Faithfulness")
        ax.set_xlim(0, 1)

    axes[0].set_ylabel("Count")
    axes[0].legend(fontsize=9)
    fig.suptitle("Baseline faithfulness distributions: clean vs poisoned", y=1.02)
    save("fig01_baseline_calibration.png")


# fig02

def fig02(df: pd.DataFrame):
    cond_labels = {
        "baseline":       "Baseline",
        "postfilter":     "Postfilter (stat)",
        "postfilter_llm": "Postfilter (LLM)",
    }
    # Baseline True means for Delta annotations
    baseline_true = {
        j: df[(df["condition"]=="baseline")&(df["judge"]==j)&(df["category"]=="True")]["faithfulness"].mean()
        for j in JUDGE_ORDER
    }

    x = np.arange(len(JUDGE_ORDER))
    w = 0.18
    offsets = np.array([-1.5, -0.5, 0.5, 1.5]) * w

    fig, axes = plt.subplots(1, 3, figsize=(13, 4.5), sharey=True)
    cat_configs = [
        ("Clean",    None,    C["Clean"],    None),
        ("Standard", None,    C["Standard"], None),
        ("True",     True,    C["True"],     "//"),
        ("Survived", None,    C["Survived"], None),
    ]

    for ax, condition in zip(axes, ["baseline", "postfilter", "postfilter_llm"]):
        for i, (cat, is_std, col, hatch) in enumerate(cat_configs):
            vals = []
            for judge in JUDGE_ORDER:
                sub = df[(df["condition"]==condition) & (df["judge"]==judge)]
                if cat == "Standard":
                    v = sub[sub["is_poisoned"]==True]["faithfulness"].mean()
                else:
                    v = sub[sub["category"]==cat]["faithfulness"].mean()
                vals.append(v)

            ax.bar(x + offsets[i], vals, w, color=col, hatch=hatch,
                   edgecolor="white" if hatch is None else "black", lw=0.5,
                   label=cat if ax == axes[0] else "_nolegend_")

        # Delta annotation on True bars
        if condition != "baseline":
            for xi, judge in enumerate(JUDGE_ORDER):
                true_now  = df[(df["condition"]==condition)&(df["judge"]==judge)&(df["category"]=="True")]["faithfulness"].mean()
                true_base = baseline_true[judge]
                delta = true_now - true_base
                ax.annotate(
                    f"Delta{delta:+.2f}",
                    xy=(xi + offsets[2], true_now),
                    xytext=(xi + offsets[2], min(true_now + 0.07, 0.99)),
                    ha="center", fontsize=8, color=C["True"],
                    arrowprops=dict(arrowstyle="->", color=C["True"], lw=0.8),
                )

        ax.set_title(cond_labels[condition])
        ax.set_xticks(x)
        ax.set_xticklabels([JUDGE_LABELS[j] for j in JUDGE_ORDER], fontsize=8.5)
        ax.set_ylim(0, 1.12)
        if ax == axes[0]:
            ax.set_ylabel("Mean faithfulness")

    axes[0].legend(fontsize=9, ncol=2, loc="upper left")
    fig.suptitle("Faithfulness by category across judging conditions", y=1.02)
    save("fig02_paradox_headline.png")


# fig03

def fig03(paradox_noise: pd.DataFrame):
    line_cfg = [
        ("baseline",       C["Clean"],        "-",  "o", "Baseline"),
        ("postfilter",     C["Postfilter"],    "--", "s", "Postfilter (stat)"),
        ("postfilter_llm", C["PostfilterLLM"], ":",  "^", "Postfilter (LLM)"),
    ]
    fig, axes = plt.subplots(1, 3, figsize=(13, 4), sharey=True)

    for ax, judge in zip(axes, JUDGE_ORDER):
        pf_vals = None
        for condition, col, ls, mk, label in line_cfg:
            sub = (paradox_noise[(paradox_noise["judge"]==judge) &
                                  (paradox_noise["condition"]==condition) &
                                  (paradox_noise["metric"]=="faithfulness")]
                   .sort_values("noise_level"))
            ax.plot(sub["noise_level"], sub["true_mean"], color=col, ls=ls,
                    marker=mk, ms=5, label=label)
            if condition == "postfilter":
                pf_vals = sub

        # Annotate postfilter at noise=0.2 and 0.8
        if pf_vals is not None:
            for nl in [0.2, 0.8]:
                row = pf_vals[pf_vals["noise_level"] == nl]
                if not row.empty:
                    v = row.iloc[0]["true_mean"]
                    ax.annotate(f"{v:.2f}", xy=(nl, v),
                                xytext=(nl + 0.04, v + 0.04),
                                fontsize=8, color=C["Postfilter"],
                                arrowprops=dict(arrowstyle="-", color=C["Postfilter"], lw=0.7))

        ax.set_title(JUDGE_LABELS[judge])
        ax.set_xlabel("Noise level")
        ax.set_xticks(NOISE_LEVELS)
        ax.set_ylim(0, 1.0)

    axes[0].set_ylabel("True-category mean faithfulness")
    axes[0].legend(fontsize=9)
    fig.suptitle("True-category faithfulness by noise level", y=1.02)
    save("fig03_true_mean_by_noise.png")


# fig04 (a/b/c)

def fig04(df: pd.DataFrame, metric: str, letter: str):
    metric_labels = {
        "faithfulness":      "Faithfulness",
        "context_relevance": "Context Relevance",
        "answer_relevance":  "Answer Relevance",
    }
    cond_cfg = [
        ("baseline",       C["Clean"],        "Baseline-True"),
        ("postfilter",     C["Postfilter"],    "Postfilter-True"),
        ("postfilter_llm", C["PostfilterLLM"], "PostfilterLLM-True"),
    ]
    x = np.arange(len(cond_cfg))
    w = 0.45

    fig, axes = plt.subplots(3, 3, figsize=(12, 9), sharey=True)

    for ji, judge in enumerate(JUDGE_ORDER):
        for ii, inj in enumerate(INJ_ORDER):
            ax = axes[ii][ji]
            vals = []
            for cond, col, lbl in cond_cfg:
                v = df[(df["condition"]==cond) & (df["judge"]==judge) &
                       (df["injection_type"]==inj) & (df["category"]=="True")][metric].mean()
                vals.append(v)
            bars = ax.bar(x, vals, w, color=[col for _, col, _ in cond_cfg])

            # Delta annotations vs baseline
            for bi in [1, 2]:
                if not (np.isnan(vals[0]) or np.isnan(vals[bi])):
                    delta = vals[bi] - vals[0]
                    ax.text(bi, vals[bi] + 0.02, f"{delta:+.2f}",
                            ha="center", fontsize=7.5,
                            color=cond_cfg[bi][1], fontweight="bold")

            ax.set_xticks(x)
            ax.set_xticklabels(["Base", "Stat", "LLM"], fontsize=8)
            ax.set_ylim(0, 1.15)
            if ii == 0:
                ax.set_title(JUDGE_LABELS[judge], fontsize=10)
            if ji == 0:
                ax.set_ylabel(INJ_LABELS[inj], fontsize=9)

    patches = [mpatches.Patch(color=col, label=lbl) for _, col, lbl in cond_cfg]
    fig.legend(handles=patches, loc="lower center", ncol=3, fontsize=9, bbox_to_anchor=(0.5, -0.01))
    fig.suptitle(f"True-category {metric_labels[metric]} by injection type and judge", y=1.01)
    plt.tight_layout()
    fname = f"fig04{letter}_per_injection_{metric.split('_')[0]}.png"
    save(fname)


# fig05

def fig05(audit: pd.DataFrame):
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    ft_labels = {"statistical": "Statistical filter", "llm": "LLM filter (Mistral)"}

    for ax, ft in zip(axes, ["statistical", "llm"]):
        pois = audit[(audit["filter_type"]==ft) & (audit["is_originally_poisoned"]==True)]
        y = np.arange(len(INJ_ORDER))
        h = 0.30

        for yi, inj in enumerate(INJ_ORDER):
            sub = pois[pois["injection_type"] == inj]
            pre_true  = int(sub["support_killed_originally"].sum())
            pre_surv  = int((~sub["support_killed_originally"]).sum())
            post_true = int(sub["support_killed_after_filter"].sum())
            post_surv = int((~sub["support_killed_after_filter"]).sum())

            # Pre-filter row (darker)
            ax.barh(yi + h/2 + 0.02, pre_true, h, color=C["True"],     label="True (pre)"     if yi==0 else "")
            ax.barh(yi + h/2 + 0.02, pre_surv, h, left=pre_true,
                    color=C["Survived"], label="Survived (pre)" if yi==0 else "")
            # Post-filter row (lighter)
            ax.barh(yi - h/2 - 0.02, post_true, h, color=C["True"],    alpha=0.45, label="True (post)"    if yi==0 else "")
            ax.barh(yi - h/2 - 0.02, post_surv, h, left=post_true,
                    color=C["Survived"], alpha=0.45, label="Survived (post)" if yi==0 else "")

            # Counts
            for val, left, row_y in [(pre_true, 0, yi+h/2+0.02),
                                      (pre_surv, pre_true, yi+h/2+0.02),
                                      (post_true, 0, yi-h/2-0.02),
                                      (post_surv, post_true, yi-h/2-0.02)]:
                if val > 10:
                    ax.text(left + val/2, row_y, str(val), ha="center", va="center", fontsize=7.5)

        ax.set_yticks(y)
        ax.set_yticklabels([INJ_LABELS[i] for i in INJ_ORDER])
        ax.set_xlabel("Triplet count")
        ax.set_title(ft_labels[ft])
        ax.legend(fontsize=8, loc="lower right")

    fig.suptitle("Filter effect: True / Survived split before and after filtering", y=1.02)
    plt.tight_layout()
    save("fig05_filter_behaviour.png")


# fig06

def fig06(df: pd.DataFrame, var_tbl: pd.DataFrame):
    base = df[df["condition"]=="baseline"][["triplet_id","judge","faithfulness","is_poisoned"]].dropna()
    pivot = base.pivot_table(index=["triplet_id","is_poisoned"], columns="judge",
                             values="faithfulness").dropna()
    if pivot.empty:
        print("  WARNING: not enough data for fig06")
        return

    cols = [c for c in JUDGE_ORDER if c in pivot.columns]
    if len(cols) < 2:
        print("  WARNING: fewer than 2 judges for fig06")
        return
    pivot["std"] = pivot[cols].std(axis=1, ddof=1)
    is_p = pivot.index.get_level_values("is_poisoned").astype(bool)

    fig, ax = plt.subplots(figsize=(7, 4))
    bins = np.linspace(0, 0.65, 30)
    ax.hist(pivot.loc[~is_p, "std"], bins=bins, alpha=0.6, color=C["Clean"], label="Clean")
    ax.hist(pivot.loc[is_p,  "std"], bins=bins, alpha=0.6, color=C["True"],  label="Poisoned")

    note = ""
    if not var_tbl.empty:
        v = var_tbl.iloc[0]
        p_str = "p < 0.001" if v["p_value"] < 0.001 else f"p = {v['p_value']:.3f}"
        note = f"r = {v['pearson_r']:+.3f},  {p_str}"
    ax.text(0.97, 0.95, note, transform=ax.transAxes, ha="right", va="top", fontsize=9)
    ax.set_xlabel("Per-triplet faithfulness std across judges")
    ax.set_ylabel("Count")
    ax.set_title("Inter-judge faithfulness disagreement: clean vs poisoned")
    ax.legend(fontsize=9)
    save("fig06_inter_judge_variance.png")


# fig07

def fig07(mcnemar: pd.DataFrame):
    sub = mcnemar[(mcnemar["metric"]=="faithfulness") & (mcnemar["category"]=="True")]
    if sub.empty:
        print("  WARNING: no McNemar True data for fig07 - skipping")
        return

    cond_pairs = [("baseline","postfilter"), ("baseline","postfilter_llm")]
    pair_labels = {"postfilter": "->Postfilter-stat", "postfilter_llm": "->Postfilter-LLM"}

    chi2_mat = np.full((len(JUDGE_ORDER), len(cond_pairs)), np.nan)
    p_mat    = np.full_like(chi2_mat, np.nan)

    for ji, judge in enumerate(JUDGE_ORDER):
        for ci, (ca, cb) in enumerate(cond_pairs):
            row = sub[(sub["judge"]==judge) & (sub["condition_a"]==ca) & (sub["condition_b"]==cb)]
            if not row.empty:
                chi2_mat[ji, ci] = row.iloc[0]["chi2"]
                p_mat[ji, ci]    = row.iloc[0]["p_value"]

    fig, ax = plt.subplots(figsize=(7, 3))
    im = ax.imshow(chi2_mat, cmap="Reds", aspect="auto", vmin=0)
    plt.colorbar(im, ax=ax, label="chi-square")
    ax.set_xticks(range(len(cond_pairs)))
    ax.set_xticklabels([pair_labels[cb] for _, cb in cond_pairs])
    ax.set_yticks(range(len(JUDGE_ORDER)))
    ax.set_yticklabels([JUDGE_LABELS[j] for j in JUDGE_ORDER])

    for ji in range(len(JUDGE_ORDER)):
        for ci in range(len(cond_pairs)):
            c2 = chi2_mat[ji, ci]
            pv = p_mat[ji, ci]
            if np.isnan(c2):
                continue
            star = "***" if pv < 0.001 else ("**" if pv < 0.01 else ("*" if pv < 0.05 else "n.s."))
            ax.text(ci, ji, f"{c2:.1f}\n{star}", ha="center", va="center", fontsize=9)

    ax.set_title("McNemar chi-square (faithfulness, True category)")
    save("fig07_mcnemar.png")


# fig08

def fig08(audit_sum: pd.DataFrame):
    cols_cfg = [
        ("mean_poisoned_passages_caught",             "#c44e52", "Poisoned caught (correct)"),
        ("mean_poisoned_passages_missed",             "#f2a0a3", "Poisoned missed"),
        ("mean_supporting_passages_lost_collateral",  "#dd8452", "Supporting lost (collateral)"),
        ("mean_distractor_passages_removed_correctly","#aaaaaa", "Distractor removed (correct)"),
    ]

    x = np.arange(len(INJ_ORDER))
    n = len(cols_cfg)
    w = 0.17
    offsets = np.linspace(-(n-1)*w/2, (n-1)*w/2, n)

    fig, axes = plt.subplots(1, 2, figsize=(12, 4), sharey=True)
    ft_labels = {"statistical": "Statistical filter", "llm": "LLM filter (Mistral)"}

    for ax, ft in zip(axes, ["statistical", "llm"]):
        sub = audit_sum[audit_sum["filter_type"] == ft]
        for bi, (col_name, col, label) in enumerate(cols_cfg):
            vals = [sub[sub["injection_type"]==inj][col_name].values[0]
                    if not sub[sub["injection_type"]==inj].empty else 0
                    for inj in INJ_ORDER]
            ax.bar(x + offsets[bi], vals, w, color=col,
                   label=label if ft=="statistical" else "_nolegend_")

            # Bold annotation for collateral-loss bars
            if col_name == "mean_supporting_passages_lost_collateral":
                for xi, v in zip(x + offsets[bi], vals):
                    if v > 0.005:
                        ax.text(xi, v + 0.01, f"{v:.3f}", ha="center", fontsize=8,
                                color=col, fontweight="bold")

        ax.set_xticks(x)
        ax.set_xticklabels([INJ_LABELS[i] for i in INJ_ORDER], fontsize=9)
        ax.set_xlabel("Injection type")
        ax.set_title(ft_labels[ft])
        if ft == "statistical":
            ax.set_ylabel("Mean passages per poisoned triplet")

    axes[0].legend(fontsize=8, loc="upper right", ncol=1)
    fig.suptitle("Filter audit: passage outcomes by injection type", y=1.02)
    plt.tight_layout()
    save("fig08_filter_audit.png")


